export type IngredientId = (typeof INGREDIENTS)[number]['id'];

const all: readonly Ingredient[] = INGREDIENTS;

export const byId: ReadonlyMap<string, Ingredient> = new Map(all.map((i) => [i.id, i]));

export const byCategory: Readonly<Record<Category, readonly Ingredient[]>> = {
  bread: all.filter((i) => i.category === 'bread'),
  protein: all.filter((i) => i.category === 'protein'),
  cheese: all.filter((i) => i.category === 'cheese'),
  veggie: all.filter((i) => i.category === 'veggie'),
  sauce: all.filter((i) => i.category === 'sauce'),
  seasoning: all.filter((i) => i.category === 'seasoning'),
  extra: all.filter((i) => i.category === 'extra'),
};

export function ing(id: string): Ingredient {
  const found = byId.get(id);
  if (!found) throw new Error(`Unknown ingredient: ${id}`);
  return found;
}

